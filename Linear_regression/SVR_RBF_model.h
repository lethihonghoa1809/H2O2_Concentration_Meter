/*
============================================================
STANDARD SCALER
============================================================
*/

static void SVR_standardize(
    float A,
    float C_LR,
    float *A_scaled,
    float *C_LR_scaled
)
{
    *A_scaled =
        (A - scaler_mean[0])
        / scaler_scale[0];

    *C_LR_scaled =
        (C_LR - scaler_mean[1])
        / scaler_scale[1];
}


/*
============================================================
SVR-RBF RESIDUAL PREDICTION
============================================================

Residual =
    SUM(
        alpha_i *
        exp(
            -gamma * distance
        )
    )
    + intercept
============================================================
*/

static float SVR_RBF_predict(
    float A,
    float C_LR
)
{
    float A_scaled;
    float C_LR_scaled;

    float residual = 0.0f;

    float dx_A;
    float dx_C;

    float distance;
    float kernel;


    // --------------------------------------------
    // StandardScaler
    // --------------------------------------------

    SVR_standardize(
        A,
        C_LR,
        &A_scaled,
        &C_LR_scaled
    );


    // --------------------------------------------
    // Support Vector calculation
    // --------------------------------------------

    for (
        uint8_t i = 0;
        i < SVR_N_SUPPORT;
        i++
    )
    {

        dx_A =
            A_scaled
            - support_vectors[i][0];


        dx_C =
            C_LR_scaled
            - support_vectors[i][1];


        distance =
            dx_A * dx_A
            +
            dx_C * dx_C;


        kernel =
            expf(
                -SVR_GAMMA
                * distance
            );


        residual +=
            dual_coef[i]
            * kernel;
    }


    // --------------------------------------------
    // Intercept
    // --------------------------------------------

    residual +=
        SVR_INTERCEPT;


    return residual;
}


/*
============================================================
H2O2 CONCENTRATION
============================================================

A =
    log10(F0 / F)

C_LR =
    (A - LR_B0) / LR_B1

Residual =
    SVR_RBF(A, C_LR)

C_SVR =
    C_LR + Residual
============================================================
*/

static float calculate_H2O2_SVR(
    float F0,
    float F
)
{
    float A;
    float C_LR;
    float residual;
    float C_SVR;


    // Kiểm tra dữ liệu
    if (
        F0 <= 0.0f ||
        F <= 0.0f
    )
    {
        return -1.0f;
    }


    // --------------------------------------------
    // A
    // --------------------------------------------

    A =
        log10f(
            F0 / F
        );


    // --------------------------------------------
    // Linear Regression
    // --------------------------------------------

    C_LR =
        (A - LR_B0)
        / LR_B1;


    // --------------------------------------------
    // SVR residual
    // --------------------------------------------

    residual =
        SVR_RBF_predict(
            A,
            C_LR
        );


    // --------------------------------------------
    // Final concentration
    // --------------------------------------------

    C_SVR =
        C_LR
        + residual;


    return C_SVR;
}

